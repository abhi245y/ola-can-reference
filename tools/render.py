#!/usr/bin/env python3
"""Generate human-readable frame and enum tables from canonical JSON."""
import argparse
from catalog import ROOT, load, profiles


def table_cell(value):
    return str(value).replace("|", "\\|").replace("\n", " ")


def render(profile):
    p = profile["profile"]
    frames = profile["frames"]
    rx = sum("headunit_rx" in f["directions"] for f in frames)
    tx = sum("headunit_tx" in f["directions"] for f in frames)
    fields = sum(len(f["signals"]) for f in frames)
    lines = [f"# {p}: frame reference", "", "Generated by `python3 tools/render.py`; edit the JSON catalog, then regenerate.", "",
             f"{len(frames)} known IDs; {rx} receive dispatches; {tx} transmit IDs; {fields} curated fields.", "",
             "Directions are relative to the Android head unit. All seed raw-CAN validation remains unverified.", "",
             "| ID | Decimal | Direction | Source names | Payload coverage |", "|---|---:|---|---|---|"]
    for frame in frames:
        lines.append(f"| {frame['id']} | {frame['decimal_id']} | {', '.join(frame['directions'])} | {table_cell(', '.join(frame['names']))} | {frame['payload_status']} |")
    for frame in frames:
        lines += ["", f"## {frame['id']} — {', '.join(frame['names'])}", "",
                  f"Direction: {', '.join(frame['directions'])}. Payload bytes: {frame['payload_bytes'] if frame['payload_bytes'] is not None else 'not established'}. Raw runtime validation: {frame['raw_runtime_validation']}.", ""]
        for parser in frame["parsers"]:
            lines.append(f"- Parser: `{parser['method']}` ({parser['body']}); evidence `{parser['evidence']}`.")
        for variant in frame["transmit_variants"]:
            lines.append(f"- `{variant['method']}`: {variant['layout']} Evidence `{variant['evidence']}`.")
        if frame["signals"]:
            lines += ["", "| Signal | LSB0 bit | Bits | Signed | Scale | Offset | Unit / enum |", "|---|---:|---:|---|---:|---:|---|"]
            for s in frame["signals"]:
                unit = s.get("enum") or s["unit"] or "unknown"
                if s["unit"] is not None and s["unit_confidence"] != "static_source":
                    unit += " (" + s["unit_confidence"] + ")"
                lines.append(f"| {s['name']} | {s['start_bit']} | {s['bit_length']} | {s['signed']} | {s['scale']} | {s['offset']} | {unit} |")
            for s in frame["signals"]:
                if s.get("notes"):
                    lines.append(f"\n{s['name']}: {s['notes']}\n")
        else:
            lines += ["", "No curated field decoder yet. A known parser or command name does not establish a complete payload."]
        for note in frame["notes"]:
            lines += ["", note]
        refs = list(dict.fromkeys(frame["evidence"] + [r for s in frame["signals"] for r in s["evidence"]]))
        lines += ["", "Sources:"]
        for ref in refs:
            source = profile["evidence"][ref]
            lines.append(f"- `{ref}`: `{source['artifact']}/{source['path']}:{source['line']}` (`{source['symbol']}`); source SHA256 `{source['source_sha256']}`.")
    enums = [f"# {p}: enum reference", "", "Generated from canonical JSON. These are version-specific source ordinals, not a cross-firmware contract.", ""]
    for name, enumeration in profile["enums"].items():
        source = profile["evidence"][enumeration["evidence"]]
        enums += [f"## {name}", "", f"{len(enumeration['values'])} entries; evidence `{enumeration['evidence']}`.",
                  f"Source: `{source['artifact']}/{source['path']}:{source['line']}`; SHA256 `{source['source_sha256']}`.",
                  "", "| Value | Hex | Source name |", "|---:|---|---|"]
        for value in enumeration["values"]:
            enums.append(f"| {value['value']} | 0x{value['value']:02X} | {value['name']} |")
        enums.append("")
    return {ROOT / "docs/generated" / (p + "-frames.md"): "\n".join(lines) + "\n",
            ROOT / "docs/generated" / (p + "-enums.md"): "\n".join(enums).rstrip() + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if committed generated tables are stale")
    args = parser.parse_args()
    stale = []
    for path in profiles():
        for target, content in render(load(path)).items():
            if args.check:
                if not target.exists() or target.read_text() != content:
                    stale.append(str(target.relative_to(ROOT)))
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(content, encoding="utf-8")
    if stale:
        raise SystemExit("Stale generated docs: " + ", ".join(stale))
    print("Generated documentation is current" if args.check else "Generated frame and enum tables")


if __name__ == "__main__":
    main()
